import ZAI from "z-ai-web-dev-sdk";
import type { RubricScores, ProctoringLog, TestCase } from "@/lib/types";

// ---------------------------------------------------------------------------
// AI helper — connects to the z-ai-web-dev-sdk LLM. If the SDK is unavailable
// (e.g. network issue or no API key configured) every function transparently
// falls back to a deterministic local heuristic analyzer so that every AI
// button in the UI still returns rich, context-aware output. This guarantees
// the platform is fully usable out-of-the-box.
// ---------------------------------------------------------------------------

let zaiSingleton: Awaited<ReturnType<typeof ZAI.create>> | null = null;

async function getZAI(): Promise<Awaited<ReturnType<typeof ZAI.create>> | null> {
  try {
    if (!zaiSingleton) {
      zaiSingleton = await ZAI.create();
    }
    return zaiSingleton;
  } catch {
    return null;
  }
}

async function chat(
  systemPrompt: string,
  userPrompt: string,
  expectJson = false
): Promise<string | null> {
  const zai = await getZAI();
  if (!zai) return null;
  try {
    const completion = await zai.chat.completions.create({
      messages: [
        { role: "assistant", content: systemPrompt },
        { role: "user", content: userPrompt },
      ],
      thinking: { type: "disabled" },
    });
    const content = completion.choices[0]?.message?.content;
    if (!content) return null;
    if (expectJson) {
      // Strip code fences if present
      const cleaned = content
        .replace(/^```(?:json)?/i, "")
        .replace(/```$/i, "")
        .trim();
      // Validate JSON parseability
      JSON.parse(cleaned);
      return cleaned;
    }
    return content;
  } catch {
    return null;
  }
}

