// FEATURE B — Live AI Co-Pilot (interviewer-only)
// ---------------------------------------------------------------------------

export interface CopilotInsight {
  complexity: { time: string; space: string };
  bugs: string[];
  edgeCases: string[];
  followUpQuestions: string[];
  hint: string;
}

function fallbackCopilot(code: string): CopilotInsight {
  const lines = code.split("\n").filter((l) => l.trim()).length;
  const hasNestedLoop = /for\s*\([^)]*\)\s*\{[\s\S]*?for\s*\(/.test(code);
  const hasHashMap = /Map\(|\{\}|hashmap|hashmap/i.test(code);
  const hasSort = /\.sort\s*\(/.test(code);
  const hasRecursion = /function\s+\w+\s*\([^)]*\)\s*\{[\s\S]*?\1/.test(code) ||
    code.includes("arguments.callee");

  return {
    complexity: {
      time: hasNestedLoop ? "O(N^2)" : hasSort ? "O(N log N)" : "O(N)",
      space: hasHashMap ? "O(N)" : "O(1)",
    },
    bugs: [
      "Check whether the loop boundary is `<=` vs `<` — off-by-one errors are the most common defect here.",
      hasHashMap
        ? "Verify the lookup key is unique; duplicate keys silently overwrite earlier values."
        : "Ensure variables are reset between iterations to avoid stale state.",
    ],
    edgeCases: [
      "Empty input array / string",
      "Single-element input",
      "All negative numbers",
      "Input containing duplicates",
      "Very large input (N > 10^5) to stress time complexity",
    ],
    followUpQuestions: [
      "How would your solution change if the input were streamed and could not fit in memory?",
      "Can you reduce the space complexity from O(N) to O(1)? What trade-off does that introduce?",
      "How would you adapt this approach if the input were sorted vs unsorted?",
      hasNestedLoop
        ? "Your current approach is O(N^2). Can you identify a two-pointer or hash-map optimization?"
        : "What is the worst-case runtime, and is it acceptable for N = 10^6?",
    ],
    hint: `Your solution has ~${lines} active lines. ${
      hasNestedLoop
        ? "A nested loop suggests O(N^2); consider a hash map to reach O(N)."
        : "Good structure — verify edge cases on empty and single-element inputs."
    }`,
  };
}

export async function analyzeCandidateCode(
  code: string,
  questionStatement?: string
): Promise<CopilotInsight> {
  const system =
    "You are an expert engineering interviewer observing a candidate write code in real time. Analyze the current code and respond with valid JSON only containing: complexity {time, space}, bugs (string[]), edgeCases (string[]), followUpQuestions (string[]), and hint (string). Be concise and specific to the code provided.";
  const user = `Question context: ${
    questionStatement ?? "(no statement provided)"
  }\n\nCandidate code:\n${code}\n\nReturn JSON shaped as:\n{\n  "complexity": { "time": string, "space": string },\n  "bugs": string[],\n  "edgeCases": string[],\n  "followUpQuestions": string[],\n  "hint": string\n}`;
  const raw = await chat(system, user, true);
  if (!raw) return fallbackCopilot(code);
  try {
    const parsed = JSON.parse(raw);
    const fb = fallbackCopilot(code);
    return {
      complexity: parsed.complexity ?? fb.complexity,
      bugs: parsed.bugs ?? fb.bugs,
      edgeCases: parsed.edgeCases ?? fb.edgeCases,
      followUpQuestions: parsed.followUpQuestions ?? fb.followUpQuestions,
      hint: parsed.hint ?? fb.hint,
    };
  } catch {
    return fallbackCopilot(code);
  }
}

