export interface AssessmentBlueprint {
  title: string;
  summary: string;
  recommendedTopics: string[];
  questions: Array<{
    title: string;
    difficulty: string;
    tags: string[];
    statement: string;
    optimalTime: string;
    optimalSpace: string;
    starterCode: string;
    publicTests: TestCase[];
    hiddenTests: TestCase[];
  }>;
  rubricWeights: Record<string, number>;
}

const FALLBACK_TOPICS = [
  "Arrays & Hashing",
  "Two Pointers",
  "Sliding Window",
  "Binary Search",
  "Trees",
  "Graphs",
  "Dynamic Programming",
  "System Design",
];

function fallbackBlueprint(jd: string): AssessmentBlueprint {
  const lower = jd.toLowerCase();
  const wantsFrontend =
    lower.includes("frontend") || lower.includes("react") || lower.includes("ui");
  const wantsBackend =
    lower.includes("backend") ||
    lower.includes("api") ||
    lower.includes("server");
  const wantsSystem =
    lower.includes("system design") ||
    lower.includes("scale") ||
    lower.includes("distributed");

  return {
    title: "AI-Generated Assessment (local heuristic)",
    summary:
      "Generated by the offline heuristic analyzer because the LLM endpoint was unavailable. Tailored to keywords detected in the provided job description.",
    recommendedTopics: wantsSystem
      ? ["System Design", "Graphs", "Dynamic Programming", "Trees"]
      : wantsFrontend
      ? ["Arrays & Hashing", "Sliding Window", "Two Pointers", "Trees"]
      : wantsBackend
      ? ["Hash Maps", "Heaps", "Graphs", "Dynamic Programming"]
      : FALLBACK_TOPICS,
    questions: [
      {
        title: "Two Sum",
        difficulty: "Easy",
        tags: ["Arrays", "Hashing"],
        statement:
          "Given an array of integers `nums` and an integer `target`, return indices of the two numbers such that they add up to target. You may assume each input has exactly one solution.",
        optimalTime: "O(N)",
        optimalSpace: "O(N)",
        starterCode:
          "/**\n * @param {number[]} nums\n * @param {number} target\n * @return {number[]}\n */\nfunction twoSum(nums, target) {\n  \n}",
        publicTests: [
          {
            input: "[[2,7,11,15],9]",
            expectedOutput: "[0,1]",
            explanation: "nums[0] + nums[1] == 9",
          },
        ],
        hiddenTests: [
          { input: "[[3,2,4],6]", expectedOutput: "[1,2]" },
          { input: "[[3,3],6]", expectedOutput: "[0,1]" },
        ],
      },
      {
        title: "Longest Substring Without Repeating Characters",
        difficulty: "Medium",
        tags: ["Sliding Window", "Strings"],
        statement:
          "Given a string `s`, find the length of the longest substring without repeating characters.",
        optimalTime: "O(N)",
        optimalSpace: "O(min(N, charset))",
        starterCode:
          "/**\n * @param {string} s\n * @return {number}\n */\nfunction lengthOfLongestSubstring(s) {\n  \n}",
        publicTests: [
          {
            input: '["abcabcbb"]',
            expectedOutput: "3",
            explanation: "The answer is 'abc' with length 3.",
          },
        ],
        hiddenTests: [
          { input: '["bbbbb"]', expectedOutput: "1" },
          { input: '["pwwkew"]', expectedOutput: "3" },
        ],
      },
      {
        title: "LRU Cache Design",
        difficulty: "Medium",
        tags: ["Design", "Hashing", "Linked List"],
        statement:
          "Design a data structure that follows the constraints of a Least Recently Used (LRU) cache. Implement get(key) and put(key, value) in O(1) average time.",
        optimalTime: "O(1)",
        optimalSpace: "O(capacity)",
        starterCode:
          "/**\n * @param {number} capacity\n */\nfunction LRUCache(capacity) {\n  \n}\nLRUCache.prototype.get = function(key) {\n  \n};\nLRUCache.prototype.put = function(key, value) {\n  \n};",
        publicTests: [
          {
            input: '[2,"get/put sequence"]',
            expectedOutput: '"see description"',
            explanation: "Validate O(1) operations over a mixed sequence.",
          },
        ],
        hiddenTests: [
          { input: '[2,"put(1,1),put(2,2),get(1)"]', expectedOutput: "1" },
        ],
      },
    ],
    rubricWeights: {
      problemSolving: 30,
      cleanCode: 20,
      optimization: 20,
      communication: 15,
      edgeCases: 15,
    },
  };
}

export async function generateAssessmentFromJD(
  jd: string
): Promise<AssessmentBlueprint> {
  const system =
    "You are a senior technical hiring architect. Given a job description, output a JSON assessment blueprint with recommended DSA topics, 3 tailored coding problems (each with statement, optimal complexity, JavaScript starter code, public + hidden test cases using JSON-encoded args), and rubric weights. Respond with valid JSON only.";
  const user = `Job Description:\n${jd}\n\nReturn JSON shaped as:\n{\n  "title": string,\n  "summary": string,\n  "recommendedTopics": string[],\n  "questions": [{ "title": string, "difficulty": "Easy"|"Medium"|"Hard", "tags": string[], "statement": string, "optimalTime": string, "optimalSpace": string, "starterCode": string, "publicTests": [{ "input": string, "expectedOutput": string, "explanation": string }], "hiddenTests": [{ "input": string, "expectedOutput": string }] }],\n  "rubricWeights": { "problemSolving": number, "cleanCode": number, "optimization": number, "communication": number, "edgeCases": number }\n}`;
  const raw = await chat(system, user, true);
  if (!raw) return fallbackBlueprint(jd);
  try {
    const parsed = JSON.parse(raw);
    // Merge so missing fields don't crash the UI.
    const fb = fallbackBlueprint(jd);
    return {
      title: parsed.title ?? fb.title,
      summary: parsed.summary ?? fb.summary,
      recommendedTopics: parsed.recommendedTopics ?? fb.recommendedTopics,
      questions: (parsed.questions ?? fb.questions).slice(0, 3),
      rubricWeights: parsed.rubricWeights ?? fb.rubricWeights,
    };
  } catch {
    return fallbackBlueprint(jd);
  }
}

