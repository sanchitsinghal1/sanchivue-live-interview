// FEATURE C — Evidence-based post-interview summary
// ---------------------------------------------------------------------------

export interface EvaluationSummary {
  evidenceSummary: string;
  strengths: string[];
  concerns: string[];
  recommendation: "STRONG_HIRE" | "HIRE" | "LEAN_HIRE" | "NO_HIRE";
}

function fallbackSummary(
  rubric: RubricScores,
  logs: ProctoringLog[],
  passedRatio: number
): EvaluationSummary {
  const total =
    rubric.problemSolving +
    rubric.cleanCode +
    rubric.optimization +
    rubric.communication +
    rubric.edgeCases;
  const max = 50;
  const pct = (total / max) * 100;
  const highSeverity = logs.filter((l) => l.severity === "high").length;

  let recommendation: EvaluationSummary["recommendation"];
  if (pct >= 85 && highSeverity === 0) recommendation = "STRONG_HIRE";
  else if (pct >= 65) recommendation = "HIRE";
  else if (pct >= 45) recommendation = "LEAN_HIRE";
  else recommendation = "NO_HIRE";

  return {
    evidenceSummary: `The candidate scored ${total}/${max} across the structured rubric, passing ${passedRatio}% of hidden test cases. ${
      highSeverity > 0
        ? `${highSeverity} high-severity proctoring alerts were logged and warrant a follow-up conversation. `
        : "No high-severity proctoring alerts were recorded. "
    }Communication and problem-solving signals should be weighted alongside the technical metrics when making the final hiring decision.`,
    strengths: [
      rubric.problemSolving >= 7 ? "Strong algorithmic decomposition" : "Improving decomposition approach",
      rubric.cleanCode >= 7 ? "Readable, well-named code" : "Code clarity can improve",
      rubric.optimization >= 7 ? "Aware of complexity trade-offs" : "Optimization awareness is developing",
    ].filter(Boolean),
    concerns: [
      highSeverity > 0
        ? `${highSeverity} high-severity proctoring alerts flagged`
        : null,
      rubric.edgeCases < 5 ? "Edge-case handling needs reinforcement" : null,
      passedRatio < 70 ? "Hidden test-case pass rate below 70%" : null,
    ].filter(Boolean) as string[],
    recommendation,
  };
}

export async function generateEvaluationSummary(
  rubric: RubricScores,
  logs: ProctoringLog[],
  passedRatio: number,
  notes: string
): Promise<EvaluationSummary> {
  const system =
    "You are a senior engineering manager producing an evidence-based interview summary. Never make an autonomous hiring decision — surface evidence objectively. Respond with valid JSON only.";
  const user = `Rubric scores (0-10 each): ${JSON.stringify(
    rubric
  )}\nHidden test pass ratio: ${passedRatio}%\nProctoring alerts: ${JSON.stringify(
    logs
  )}\nInterviewer notes: ${notes}\n\nReturn JSON shaped as:\n{\n  "evidenceSummary": string,\n  "strengths": string[],\n  "concerns": string[],\n  "recommendation": "STRONG_HIRE"|"HIRE"|"LEAN_HIRE"|"NO_HIRE"\n}`;
  const raw = await chat(system, user, true);
  if (!raw) return fallbackSummary(rubric, logs, passedRatio);
  try {
    const parsed = JSON.parse(raw);
    const fb = fallbackSummary(rubric, logs, passedRatio);
    return {
      evidenceSummary: parsed.evidenceSummary ?? fb.evidenceSummary,
      strengths: parsed.strengths ?? fb.strengths,
      concerns: parsed.concerns ?? fb.concerns,
      recommendation: parsed.recommendation ?? fb.recommendation,
    };
  } catch {
    return fallbackSummary(rubric, logs, passedRatio);
  }
}
